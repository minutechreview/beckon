// One row per notifiable transition. The unique key makes "notify at most once
// per transition" hold across server instances: whoever inserts first decides.
// Rate limits are computed from `created_at` of rows with outcome 'sent', so
// they hold across instances too.
export const notifications = pgTable(
  "notifications",
  {
    id: id(),
    userId: uuid("user_id").notNull().references(() => users.id, { onDelete: "cascade" }),
    sessionId: uuid("session_id").notNull().references(() => sessions.id, { onDelete: "cascade" }),
    path: text("path").notNull(),
    revision: bigint("revision", { mode: "number" }).notNull(),
    state: text("state").notNull(),
    kind: text("kind"),
    // sent | toast | quiet_hours | disabled | rate_limited | collapsed
    outcome: text("outcome").notNull(),
    createdAt: ts("created_at").notNull().defaultNow(),
    summarizedAt: ts("summarized_at"), // collapsed rows: set when a summary push covered them
  },
  (t) => [
    uniqueIndex("notifications_transition_uq").on(t.sessionId, t.path, t.revision),
    index("notifications_user_sent_idx").on(t.userId, t.createdAt).where(sql`outcome = 'sent'`),
    index("notifications_path_sent_idx").on(t.sessionId, t.path, t.createdAt).where(sql`outcome = 'sent'`),
    index("notifications_collapsed_idx").on(t.userId, t.createdAt).where(sql`outcome = 'collapsed' and summarized_at is null`),
  ],
);

