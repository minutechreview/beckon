export const deviceCodes = pgTable("device_codes", {
  id: id(),
  deviceCodeHash: text("device_code_hash").notNull().unique(),
  userCode: text("user_code").notNull().unique(),
  label: text("label").notNull(),
  // The helper's freshly generated public keys, copied to the host on approval.
  signPubkey: bytea("sign_pubkey").notNull(),
  boxPubkey: bytea("box_pubkey").notNull(),
  status: text("status").notNull().default("pending"), // pending | approved | consumed
  userId: uuid("user_id").references(() => users.id, { onDelete: "cascade" }),
  hostId: uuid("host_id").references(() => hosts.id, { onDelete: "set null" }),
  createdAt: ts("created_at").notNull().defaultNow(),
  expiresAt: ts("expires_at").notNull(),
}, (t) => [
  check("device_codes_status_chk", sql`${t.status} in ('pending','approved','consumed')`),
  key32("device_codes_sign_pubkey_len", t.signPubkey),
  key32("device_codes_box_pubkey_len", t.boxPubkey),
]);

