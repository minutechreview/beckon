// ---- M5: signed responses (SPEC §6, §7.4) ----

export const RESPONSE_STATUSES = [
  "pending", // stored, not yet handed to the host's socket
  "delivered", // sent to the helper running the session
  "applied", // the helper verified it and typed the option's keys
  "rejected_stale", // the record moved on, was answered (here or at the keyboard), or the server refused it
  "rejected_sig", // signature, key or decryption check failed (on the server or the host)
  "rejected_replay", // the host has seen its nonce before
  "rejected_option", // the option was not offered for that revision
  "rejected_disabled", // the session runs with --no-respond
  "expired", // never applied within the freshness window
] as const;
export type ResponseStatus = (typeof RESPONSE_STATUSES)[number];

// One row per response attempt, kept as the audit trail (SPEC §8.4). The
// payload is sealed to the host's box key: the server cannot read which
// option was picked, and option keystrokes never exist off the host at all.
export const responses = pgTable(
  "responses",
  {
    id: uuid("id").primaryKey(), // the device's response_id, covered by its signature
    userId: uuid("user_id").notNull().references(() => users.id, { onDelete: "cascade" }),
    sessionId: uuid("session_id").notNull().references(() => sessions.id, { onDelete: "cascade" }),
    path: text("path").notNull(),
    recordRevision: bigint("record_revision", { mode: "number" }).notNull(),
    deviceId: uuid("device_id").notNull().references(() => devices.id, { onDelete: "cascade" }),
    encPayload: bytea("enc_payload").notNull(), // crypto_box_seal to the host
    signature: bytea("signature").notNull(), // Ed25519 by the device
    status: text("status").notNull().default("pending"),
    createdAt: ts("created_at").notNull().defaultNow(),
    resolvedAt: ts("resolved_at"),
  },
  (t) => [
    check("responses_status_chk", sql.raw(`status in (${RESPONSE_STATUSES.map((s) => `'${s}'`).join(",")})`)),
    check("responses_signature_len", sql`octet_length(${t.signature}) = 64`),
    index("responses_session_idx").on(t.sessionId, t.createdAt),
    index("responses_device_idx").on(t.deviceId, t.createdAt),
    index("responses_open_idx").on(t.createdAt).where(sql`status in ('pending','delivered')`),
  ],
);

