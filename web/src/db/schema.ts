import { sql } from "drizzle-orm";
import {
  bigint,
  boolean,
  check,
  customType,
  index,
  integer,
  jsonb,
  pgTable,
  primaryKey,
  smallint,
  text,
  time,
  timestamp,
  uniqueIndex,
  uuid,
} from "drizzle-orm/pg-core";
import { uuidv7 } from "uuidv7";

const bytea = customType<{ data: Buffer; driverData: Buffer }>({
  dataType: () => "bytea",
});

/** A 32-byte public key column constraint. */
const key32 = (name: string, col: unknown) => check(name, sql`octet_length(${col}) = 32`);

const id = () => uuid("id").primaryKey().$defaultFn(() => uuidv7());
const ts = (name: string) => timestamp(name, { withTimezone: true, mode: "date" });

// ---- Auth.js tables (JWT session strategy, so no auth sessions table) ----

export const users = pgTable("users", {
  id: id(),
  email: text("email").notNull().unique(),
  emailVerified: ts("email_verified"),
  name: text("name"),
  image: text("image"),
  createdAt: ts("created_at").notNull().defaultNow(),
  // ---- M7: plan and billing (SPEC §10). Written only by the Stripe webhook. ----
  plan: text("plan").notNull().default("free"), // free | pro
  planStatus: text("plan_status").notNull().default("none"), // none | active | past_due
  planPeriodEnd: ts("plan_period_end"), // end of the paid period
  cancelAtPeriodEnd: boolean("cancel_at_period_end").notNull().default(false),
  pastDueSince: ts("past_due_since"), // start of the 7-day grace period
  stripeCustomerId: text("stripe_customer_id").unique(),
  stripeSubscriptionId: text("stripe_subscription_id"),
  // On Free with several hosts (after a downgrade): the one that stays enabled.
  freeHostId: uuid("free_host_id"),
  planEventAt: ts("plan_event_at"), // created time of the newest Stripe event applied: older ones are ignored
}, (t) => [
  check("users_plan_chk", sql`${t.plan} in ('free','pro')`),
  check("users_plan_status_chk", sql`${t.planStatus} in ('none','active','past_due')`),
]);

