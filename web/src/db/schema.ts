// Browsers/phones that view (and in M5 answer). Public keys only: private
// keys stay in the browser's IndexedDB.
export const devices = pgTable(
  "devices",
  {
    id: id(),
    userId: uuid("user_id").notNull().references(() => users.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    signPubkey: bytea("sign_pubkey").notNull(), // Ed25519, signs responses (M5) and revocations
    boxPubkey: bytea("box_pubkey").notNull(), // X25519, receives sealed content keys
    pushSubscription: jsonb("push_subscription"), // M4
    createdAt: ts("created_at").notNull().defaultNow(),
    lastSeenAt: ts("last_seen_at"),
    revokedAt: ts("revoked_at"),
  },
  (t) => [
    index("devices_user_idx").on(t.userId),
    uniqueIndex("devices_sign_pubkey_uq").on(t.signPubkey),
    key32("devices_sign_pubkey_len", t.signPubkey),
    key32("devices_box_pubkey_len", t.boxPubkey),
  ],
);

// A device asking a host to trust it (SPEC §8.2). The server only relays key
// bundles; trust is decided by the user confirming the safety code locally
// on the host (`beckon pair`) and on the device ("Codes match").
export const pairRequests = pgTable(
  "pair_requests",
  {
    id: id(),
    userId: uuid("user_id").notNull().references(() => users.id, { onDelete: "cascade" }),
    hostId: uuid("host_id").notNull().references(() => hosts.id, { onDelete: "cascade" }),
    deviceId: uuid("device_id").notNull().references(() => devices.id, { onDelete: "cascade" }),
    status: text("status").notNull().default("pending"), // pending | confirmed (by the host)
    createdAt: ts("created_at").notNull().defaultNow(),
    expiresAt: ts("expires_at").notNull(),
    confirmedAt: ts("confirmed_at"),
    // Commit-then-reveal (SPEC §8.2): the device's commitment to its keys and
    // nonce, the host's nonce that answers it, then the device's nonce. All
    // three are relayed; none is secret, and the server cannot use them to
    // choose keys that collide.
    commitment: bytea("commitment"),
    hostNonce: bytea("host_nonce"),
    deviceNonce: bytea("device_nonce"),
  },
  (t) => [
    check("pair_requests_status_chk", sql`${t.status} in ('pending','confirmed')`),
    index("pair_requests_host_idx").on(t.hostId),
    // At most one open request per (host, device): asking again extends it.
    uniqueIndex("pair_requests_pending_uq").on(t.hostId, t.deviceId).where(sql`status = 'pending'`),
  ],
);

// "Device X revokes device Y", signed by X. Relayed to hosts, which verify it
// against X's pinned key (SPEC §8.4).
export const deviceRevocations = pgTable(
  "device_revocations",
  {
    id: id(),
    userId: uuid("user_id").notNull().references(() => users.id, { onDelete: "cascade" }),
    deviceId: uuid("device_id").notNull().references(() => devices.id, { onDelete: "cascade" }),
    signPubkey: bytea("sign_pubkey").notNull(), // the revoked device's key, as signed
    byDeviceId: uuid("by_device_id").notNull().references(() => devices.id, { onDelete: "cascade" }),
    issuedAt: text("issued_at").notNull(),
    signature: bytea("signature").notNull(),
    createdAt: ts("created_at").notNull().defaultNow(),
  },
  (t) => [
    index("device_revocations_user_idx").on(t.userId),
    // One signed statement per revoked device is enough; retries add nothing.
    uniqueIndex("device_revocations_device_uq").on(t.deviceId),
  ],
);

